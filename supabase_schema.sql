-- 1. Create the table with a user_id column linked to Supabase Auth
CREATE TABLE transactions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id UUID DEFAULT auth.uid() NOT NULL, -- Automatically captures the logged-in user
  amount DECIMAL(12, 2) NOT NULL,
  currency VARCHAR(10) DEFAULT 'INR',
  description TEXT NOT NULL,
  category VARCHAR(50) NOT NULL,
  transaction_date DATE NOT NULL DEFAULT CURRENT_DATE,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- 2. Enable Row Level Security (RLS)
-- This "locks" the table. Now, nobody can see anything without a policy.
ALTER TABLE transactions ENABLE ROW LEVEL SECURITY;

-- 3. Create a Policy: Users can only see/edit their OWN transactions
CREATE POLICY "Users can only access their own transactions" 
ON transactions 
FOR ALL 
USING (auth.uid() = user_id) 
WITH CHECK (auth.uid() = user_id);

-- 4. Index for performance
CREATE INDEX idx_transactions_user_id ON transactions(user_id);
CREATE INDEX idx_transactions_date ON transactions(transaction_date);

